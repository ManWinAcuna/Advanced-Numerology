//   'released' (Movies/Songs, P577 publication date) - 'aired' (Shows, P580
//   start time - a series doesn't have a single "publication" the way a
//   film/song does) - 'anime' (a mixed list of series AND films, so it tries
//   P577 then P580 per entity, whichever the actual Wikidata item has).
// A group act (a band, not a solo artist) has no P569 birth date at all, so
// it simply never matches any year filter here - correct, not a bug, since
// a band doesn't have a birth year (it has a formation year, which is what
